// kradfile2 format (UTF-8): `<kanji> : <radical> <radical> ...`
function readKrad() {
  const map = {};
  const lines = fs.readFileSync(READ.krad, 'utf8').split(/\r?\n/);
  for (const line of lines) {
    const m = /^(\S+)\s*:\s*(.*)$/.exec(line.trim());
    if (!m) continue;
    const rads = (m[2] || '').split(/\s+/).filter(Boolean);
    if (rads.length) map[m[1]] = rads;
  }
  return map;
}

const VERB_END = /(る|く|ぐ|す|つ|ぬ|ぶ|む)([うっってだたなは]?)$/; // only used as hint

function classify(word, mean) {
  const m0 = (mean && mean[0]) || '';
  if (/^to\s/i.test(m0)) {
    return 'V';
  }
  // い-adjective: kanji + い ending (or known kana words)
  if (/[一-龯].*(い|しい|ない)$/.test(word) && !/(合い|違い|勝ち|負け)味?$/.test(word) && !/(賞味|物知り)$/.test(word)) return 'I';
  if (KANA_IA.indexOf(word) >= 0) return 'I';
  return 'N';
}

