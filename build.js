function themeForMeanings(meanings) {
  const hay = (meanings || []).join(' ').toLowerCase();
  let best = null, bestN = 0;
  for (const t in THEME_KEYWORDS) {
    let n = 0;
    for (const kw of THEME_KEYWORDS[t]) if (hay.includes(kw)) n++;
    if (n > bestN) { best = t; bestN = n; }
  }
  return best || 'general';
}

