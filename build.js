const CLEAN_TAGS = new Set([
  'n', 'hon', 'abbr', 'col', 'hum', 'uk', 'exp', 'arch',
  'v5u', 'v5r', 'v5s', 'female', 'vt', 'pol',
]);

function cleanMeanings(meanings) {
  return (meanings || [])
    .map((s) => (
      String(s)
        .replace(/\(([^)]*)\)/g, (all, inside) => (CLEAN_TAGS.has(inside.trim()) ? '' : all))
        .replace(/;\s*\)/g, ')')
        .replace(/\s{2,}/g, ' ')
        .replace(/\s*;\s*$/, '')
        .trim()
    ))
    .filter(Boolean);
}

function main() {
  const vocab = JSON.parse(fs.readFileSync(READ.vocab, 'utf8'));
  const kanji = JSON.parse(fs.readFileSync(READ.kanji, 'utf8'));
  const krad = readKrad();

  const kanjiMap = {};
  for (const k of kanji) {
    kanjiMap[k.character] = {
      o: k.onyomi || [],
      k: k.kunyomi || [],
      m: (k.meanings || []).slice(0, 4),
      s: k.strokes,
      l: k.level,
      rad: krad[k.character] || [],
    };
  }

  const words = vocab.map((w) => {
    const read = (w.reading && w.reading.trim()) || w.word;
    const pos = classify(w.word, w.meanings);
    const theme = themeForMeanings(w.meanings);
    const ex = (w.examples || []).slice(0, 2).map((e) => [e.ja, e.en]);
    return { w: w.word, r: read, m: cleanMeanings(w.meanings).join('; '), p: pos, t: theme, x: ex };
  });

  const data = {
    meta: {
      source: 'OpenJLPT (tanos.co.uk lists, Tatoeba examples, KANJIDIC2, kradfile2 radicals)',
      vocab: words.length,
      kanji: Object.keys(kanjiMap).length,
      rad: Object.values(kanjiMap).filter((k) => k.rad.length).length,
    },
    words,
    kanji: kanjiMap,
  };

  const js = 'window.N2GAME_DATA = ' + JSON.stringify(data) + ';';
  fs.writeFileSync(path.join(__dirname, 'n2data.js'), js);
  console.log('words:', words.length, '| kanji:', Object.keys(kanjiMap).length);
  const dist = {};
  for (const w of words) { const k = w.p; dist[k] = (dist[k] || 0) + 1; }
  console.log('POS dist:', JSON.stringify(dist));
}

